/**
 * The complete coding-interview track requested by the project owner.
 *
 * This is intentionally a navigation layer over the authored lessons, not a
 * second copy of their content. Keeping one canonical lesson per concept means
 * fixes, examples, code, quizzes and practice stay in sync everywhere.
 */
export interface DsaTrackItem {
  title: string;
  lesson: string;
  /** Section id inside the lesson (an H2 id), so the roadmap links straight to it. */
  anchor?: string;
}

export interface DsaTrackGroup {
  id: string;
  title: string;
  level: "Beginner" | "Core" | "Advanced";
  description: string;
  items: DsaTrackItem[];
}

const item = (title: string, lesson: string, anchor?: string): DsaTrackItem => ({ title, lesson, anchor });

